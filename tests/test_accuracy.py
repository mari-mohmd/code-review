"""
Regression tests for the accuracy fixes derived from the 100-commit
evaluation (see evaluation/EVALUATION.md).  Each test reproduces, in
miniature, a failure observed on pandapower or dronekit-python.

Run:  python -m unittest discover -s tests
"""
import difflib
import shutil
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lib.analyzer import ChecklistGenerator  # noqa: E402


def _diff(old: dict, new: dict) -> str:
    out = []
    for path in sorted(set(old) | set(new)):
        a = textwrap.dedent(old.get(path, "")).splitlines(keepends=True)
        b = textwrap.dedent(new.get(path, "")).splitlines(keepends=True)
        if a == b:
            continue
        out += difflib.unified_diff(a, b, f"a/{path}", f"b/{path}")
    return "".join(l if l.endswith("\n") else l + "\n" for l in out)


class Case(unittest.TestCase):
    def run_tool(self, old: dict, new: dict, extra: dict = None):
        d = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, d)
        for path, src in {**new, **(extra or {})}.items():
            p = d / path
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(textwrap.dedent(src))
        gen = ChecklistGenerator(str(d), checklist_path=None)
        return gen.generate_from_diff(_diff(old, new), False)

    @staticmethod
    def cats(items):
        return [i.category for i in items]


# ---------------------------------------------------------------- scope
class TestScope(Case):
    def test_non_python_files_are_ignored(self):
        items = self.run_tool({"docs/guide.rst": "x = 1\n"},
                              {"docs/guide.rst": "x = 1\nvalue 5 and 7\n"})
        self.assertEqual(items, [])

    def test_python2_file_reported_not_misanalysed(self):
        old = {"ex.py": "v = connect('a')\nprint 'hi'\nv.close()\n"}
        new = {"ex.py": "v = connect('a')\nprint 'hello'\nv.close()\n"}
        items = self.run_tool(old, new)
        self.assertEqual(self.cats(items), ["parse"])
        self.assertIn("not valid Python", items[0].message)

    def test_generated_file_skipped(self):
        hdr = "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n"
        items = self.run_tool({"m_pb2.py": hdr + "A = 1\n"},
                              {"m_pb2.py": hdr + "A = 1\n_ACCESSCODE = 2\nAccessCode = 3\n"})
        self.assertEqual(self.cats(items), ["skipped"])


# ---------------------------------------------------------------- formatting
class TestFormatting(Case):
    BASE = textwrap.dedent("""
    def f(a, b):
        x = g(a,
              b)
        y = 1
        z = 2
        q = 3
        w = 4
        return x + y
    """)

    def test_whitespace_only_is_no_functional_change(self):
        new = self.BASE.replace("g(a,\n          b)", "g(a, b)")
        items = self.run_tool({"m.py": self.BASE}, {"m.py": new})
        self.assertEqual(self.cats(items), ["formatting"])

    def test_cosmetic_first_hunk_does_not_mask_later_logic_change(self):
        new = self.BASE.replace("g(a,\n          b)", "g(a, b)").replace("return x + y", "return x + y + 777")
        items = self.run_tool({"m.py": self.BASE}, {"m.py": new})
        self.assertNotIn("formatting", self.cats(items))
        self.assertTrue(any("777" in i.message for i in items))

    def test_moved_import_is_not_cosmetic(self):
        old = "import os\nfrom a import *\nfrom b import *\nX = 1\n"
        new = "import os\nfrom b import *\nfrom a import *\nX = 1\n"
        items = self.run_tool({"m.py": old}, {"m.py": new})
        self.assertNotIn("formatting", self.cats(items))

    def test_docstring_only_change_runs_no_checkers(self):
        old = '''
        class Mission(object):
            """Old text about goto and clear."""
            pass

        def goto():
            """Old"""
            pass
        '''
        new = old.replace("Old text about goto and clear.", "New text about goto, clear, Mission.")
        items = self.run_tool({"m.py": old}, {"m.py": new})
        self.assertEqual(self.cats(items), ["formatting"])


# ---------------------------------------------------------------- structural divergence
class TestStructural(Case):
    def test_empty_stubs_and_cross_kind_pairs_not_reported(self):
        old = "class A(object):\n    pass\n\ndef b():\n    pass\n"
        new = old + "\ndef c():\n    pass\n\ndef d():\n    return None\n"
        items = self.run_tool({"m.py": old}, {"m.py": new})
        self.assertNotIn("structural", self.cats(items))

    def test_duplicate_definition_is_reported(self):
        body = "def lookup(net):\n    a = net['x']\n    b = a >= 0\n    return a[b]\n"
        items = self.run_tool({"m.py": body}, {"m.py": body + "\n\n" + body})
        self.assertIn("structural", self.cats(items))

    def test_copy_paste_class_is_reported(self):
        old = 'class Light:\n    type = "Light"\n\n    def __str__(self):\n        return self.type\n'
        new = old + '\nclass Heat:\n    type = "Light"\n\n    def __str__(self):\n        return self.type\n'
        items = self.run_tool({"m.py": old}, {"m.py": new})
        self.assertIn("structural", self.cats(items))


# ---------------------------------------------------------------- lifecycle
class TestLifecycle(Case):
    def test_module_level_close_later_in_file_is_seen(self):
        old = "from dk import connect\nvehicle = connect('a')\nvehicle.arm()\nvehicle.close()\n"
        new = old.replace("connect('a')", "connect('b')")
        items = self.run_tool({"ex.py": old}, {"ex.py": new})
        self.assertNotIn("lifecycle", self.cats(items))

    def test_unclosed_connection_in_function_reported_once(self):
        old = "from dk import connect\n\ndef test_x(p):\n    pass\n"
        new = "from dk import connect\n\ndef test_x(p):\n    vehicle = connect(p)\n    vehicle.arm()\n"
        items = self.run_tool({"t.py": old}, {"t.py": new})
        self.assertEqual(self.cats(items), ["lifecycle"])
        self.assertEqual(items[0].line, 4)

    def test_returned_handle_is_not_a_leak(self):
        new = "def make(p):\n    v = connect(p)\n    return v\n"
        items = self.run_tool({"m.py": "def make(p):\n    return None\n"}, {"m.py": new})
        self.assertNotIn("lifecycle", self.cats(items))

    def test_unbound_mkstemp_reported(self):
        old = "import tempfile\n\ndef f():\n    return 1\n"
        new = "import tempfile\n\ndef f():\n    return run('--log=' + tempfile.mkstemp()[1])\n"
        items = self.run_tool({"m.py": old}, {"m.py": new})
        self.assertTrue(any("mkstemp" in i.message for i in items))


# ---------------------------------------------------------------- magic numbers
class TestMagic(Case):
    def test_self_documenting_literals_are_skipped(self):
        old = "def f(net):\n    pass\n"
        new = ("def f(net, tol=1e-8):\n"
               "    create_line(net, length_km=4, r_ohm=0.256)\n"
               "    table = [0.4, 0.11, 240]\n"
               "    if sys.version_info >= (3, 8):\n"
               "        pass\n")
        items = self.run_tool({"m.py": old}, {"m.py": new})
        self.assertNotIn("magic", self.cats(items))

    def test_changed_line_and_unchanged_comparison_reported(self):
        old = "def f(bus, t):\n    s = bus[bus[:, 1] == 3]\n    return s\n"
        new = "def f(bus, t):\n    s = bus[bus[:, 1] == 3]\n    return s * 37\n"
        items = self.run_tool({"m.py": old}, {"m.py": new})
        msgs = [i.message for i in items if i.category == "magic"]
        self.assertTrue(any("37" in m for m in msgs))   # changed line
        self.assertTrue(any(" 3 " in m for m in msgs))  # unchanged comparison operand

    def test_unchanged_arithmetic_not_reported(self):
        old = "def f(x):\n    y = x * 37\n    return y\n"
        new = "def f(x):\n    y = x * 37\n    return y + x\n"
        items = self.run_tool({"m.py": old}, {"m.py": new})
        self.assertNotIn("magic", self.cats(items))

    def test_test_files_skipped(self):
        items = self.run_tool({"tests/test_a.py": "def test():\n    pass\n"},
                              {"tests/test_a.py": "def test():\n    assert f() == 42.17\n"})
        self.assertNotIn("magic", self.cats(items))


