# ---------------------------------------------------------------- injection
class TestInjection(Case):
    def check(self, line):
        items = self.run_tool({"m.py": "import json, pickle, re\n\ndef f(s):\n    pass\n"},
                              {"m.py": f"import json, pickle, re\n\ndef f(s):\n    return {line}\n"})
        return "injection" in self.cats(items)

    def test_injection_precision(self):
        self.assertFalse(self.check("json.loads(s)"))
        self.assertTrue(self.check("json.loads(s, cls=Decoder)"))
        self.assertTrue(self.check("pickle.loads(s)"))
        self.assertFalse(self.check("re.compile(s)"))
        self.assertTrue(self.check("eval(s)"))
        self.assertFalse(self.check("__import__('pandapower')"))
        self.assertTrue(self.check("__import__(s)"))


# ---------------------------------------------------------------- linkage
class TestLinkage(Case):
    def test_package_imports_and_reverse_users(self):
        files = {
            "pkg/__init__.py": "",
            "pkg/core.py": "from .util import helper\n\ndef run(x):\n    return helper(x)\n",
            "pkg/util.py": "def helper(x):\n    return x\n",
            "pkg/cli.py": "from pkg.core import run\n\nrun(1)\n",
            "pkg/other.py": "import pkg.core as c\n\nc.unrelated()\n",
        }
        new = dict(files)
        new["pkg/core.py"] = files["pkg/core.py"].replace("helper(x)", "helper(x) + 1")
        items = self.run_tool({"pkg/core.py": files["pkg/core.py"]}, {"pkg/core.py": new["pkg/core.py"]},
                              extra={k: v for k, v in files.items() if k != "pkg/core.py"})
        link = [i for i in items if i.category == "linkage"]
        self.assertEqual(len(link), 1)
        self.assertIn("pkg/util.py", link[0].detail)      # forward (relative import)
        self.assertIn("pkg/cli.py", link[0].detail)       # reverse: uses run
        self.assertNotIn("pkg/other.py", link[0].detail)  # uses only an unchanged name


# ---------------------------------------------------------------- robustness
class TestRobustness(Case):
    def test_stale_hunk_is_relocated(self):
        header = '"""\nLicense header\nadded after the diff was made\n"""\n'
        old = "x = 1\n\ndef f():\n    return 1\n"
        new = "x = 1\n\ndef f():\n    return 1 + 41\n"
        diff = _diff({"m.py": old}, {"m.py": new})
        d = Path(tempfile.mkdtemp()); self.addCleanup(shutil.rmtree, d)
        (d / "m.py").write_text(header + new)
        items = ChecklistGenerator(str(d)).generate_from_diff(diff, False)
        magic = [i for i in items if i.category == "magic"]
        self.assertEqual(len(magic), 1)
        self.assertEqual(magic[0].line, 8)


