from _paths import EVAL, WORK, TOOL  # noqa: E402
import json, collections
R = json.load(open(f"{EVAL}/v2_items.json"))
LK = json.load(open(f"{EVAL}/linkage_v2.json"))
MANUAL = {
    "dk2-18-002": ("A", "mkstemp()[1] discards an open file descriptor (real leak, missed by baseline)"),
    "dk2-28-004": ("A", "heartbeat timeout 5 s hard-coded in comparison"),
    "dk2-28-005": ("A", "parameter-request batch limit 50 hard-coded in comparison"),
    "pp2-04-003": ("A", "BUS_TYPE == 3 although REF constant exists"),
    "pp2-19-003": ("A", "solver codes alg == 545/550"),
    "pp2-19-004": ("A", "1e10 used as 'unlimited rating' sentinel"),
    "pp2-12-002": ("A", "pickle.load of file contents"),
    "pp2-12-003": ("A", "pickle.load of file contents"),
    "pp2-35-007": ("A", "import_module with module name taken from JSON input"),
    "pp2-35-008": ("A", "import_module with module name taken from JSON input"),
    "pp2-38-004": ("A", "identical example-grid functions; consolidated in 6d3e8a22a"),
    "pp2-38-005": ("A", "identical example-grid functions; consolidated in 6d3e8a22a"),
    "pp2-38-006": ("A", "identical example-grid functions; consolidated in 6d3e8a22a"),
    "pp2-38-007": ("A", "near-identical example-grid functions; consolidated in 6d3e8a22a"),
    "dk2-05-000": ("N", "protobuf-generated file correctly skipped"),
    "pp2-05-000": ("F", "Sphinx conf.py misclassified as generated ('autogenerated by sphinx-quickstart')"),
}
out = []
for r in R:
    if r["label"] is not None:
        lab, why = r["label"], r["reason"]
    elif r["id"] in MANUAL:
        lab, why = MANUAL[r["id"]]
    elif r["category"] == "linkage":
        lab, why = LK[r["id"]]["label"], LK[r["id"]]["reason"]
    elif r["category"] == "formatting":
        lab, why = "N", "verified: ASTs equal after removing docstrings"
    elif r["category"] == "parse":
        lab, why = "N", "correct: file is Python 2 and was not analysed"
    else:
        raise SystemExit("unlabelled " + r["id"])
    out.append({**{k: r[k] for k in ("id", "project", "sha", "file", "category", "message", "line", "base_id")},
                "label": lab, "reason": why})
json.dump(out, open(f"{EVAL}/labels_v2.json", "w"), indent=1)

base = json.load(open(f"{EVAL}/labels.json"))
kept = {o["base_id"] for o in out if o["base_id"]}
lost_A = [b for b in base if b["label"] == "A" and b["id"] not in kept]
print("lost A:", len(lost_A))
for b in lost_A:
    print("  ", b["id"], b["category"], b["message"], "|", b["reason"])
for p in ("dk", "pp"):
    sub = [o for o in out if o["project"] == p]
    c = collections.Counter(o["label"] for o in sub)
    print(p, len(sub), dict(c))
    t = collections.defaultdict(collections.Counter)
    for o in sub: t[o["category"]][o["label"]] += 1
    for k, v in sorted(t.items(), key=lambda kv: -sum(kv[1].values())): print("   ", k, sum(v.values()), dict(v))
